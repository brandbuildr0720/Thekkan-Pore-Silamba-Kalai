/* ── Single location card HTML ────────────────────────── */
function _locationCardHTML(b, basePath, isStudent) {
  const masterNames = b.masters.map(m => m.name).join(' & ');
  const mastersLabel = b.masters.length > 1
    ? `<span style="font-size:12px;color:var(--text-muted);font-family:'Raleway',sans-serif;font-weight:300;"> — ${b.masters.length} Instructors</span>`
    : '';
  const phones = b.phone.map(p =>
    `<a href="tel:${p.replace(/\s/g,'')}">${p}</a>`
  ).join('  ·  ');
  const emails = b.email.map(e =>
    `<a href="mailto:${e}">${e}</a>`
  ).join('<br>');
  const trainedTag = isStudent && b.trainedUnder
    ? `<span class="trained-tag">🎓 Trained under ${b.trainedUnder}</span>`
    : '';
  return `
    <div class="location-card${isStudent ? ' student-branch' : ''} scroll-reveal">
      <h3>${b.name}${mastersLabel}</h3>
      ${trainedTag}
      <p class="loc-master">${masterNames}</p>
      <p>📍 ${b.location}</p>
      <p>📞 ${phones}</p>
      <p>📧 ${emails}</p>
      <p>🕐 ${b.schedule}</p>
      <div style="margin-top:16px;">
        <a href="${basePath}${b.file}" class="view-branch-link" style="font-size:11px;letter-spacing:2px;color:var(--gold);text-transform:uppercase;border:1px solid var(--border);padding:8px 16px;transition:var(--transition);">View Branch →</a>
      </div>
    </div>`;
}

