/* ── Shared tilt hover ─────────────────────────────────── */
function _attachTilt(grid, selector) {
  if (!window.matchMedia('(hover: hover)').matches) return;
  grid.querySelectorAll(selector).forEach(card => {
    card.addEventListener('mousemove', (e) => {
      const r = card.getBoundingClientRect();
      const x = ((e.clientX - r.left) / r.width  - 0.5) * 12;
      const y = ((e.clientY - r.top)  / r.height - 0.5) * 12;
      card.style.transform = `translateY(-8px) rotateX(${-y}deg) rotateY(${x}deg)`;
    });
    card.addEventListener('mouseleave', () => { card.style.transform = ''; });
  });
}

/* ── Gallery: load images via GitHub API ──────────────── */
/**
 * Reads the contents of images/gallery/ from your GitHub repo
 * and renders every image into #galleryGrid automatically.
 *
 * Set these two variables to match your repo:
 */
const GITHUB_USER = 'brandbuildR0720';
const GITHUB_REPO = 'Thekkan-Pore-Silamba-Kalai';
const GITHUB_BRANCH_NAME = 'main';   // usually 'main' or 'master'
const GALLERY_FOLDER = 'images/gallery';

async function loadGalleryFromGitHub() {
  const grid     = document.getElementById('galleryGrid');
  const emptyMsg = document.getElementById('galleryEmpty');
  const loader   = document.getElementById('galleryLoader');
  if (!grid) return;

  try {
    const apiUrl = `https://api.github.com/repos/${GITHUB_USER}/${GITHUB_REPO}/contents/${GALLERY_FOLDER}?ref=${GITHUB_BRANCH_NAME}`;
    const res  = await fetch(apiUrl);
    if (!res.ok) throw new Error('GitHub API error: ' + res.status);
    const files = await res.json();

    const images = files.filter(f =>
      f.type === 'file' && /\.(jpg|jpeg|png|webp|gif)$/i.test(f.name)
    );

    if (loader) loader.style.display = 'none';

    if (images.length === 0) {
      if (emptyMsg) emptyMsg.style.display = 'block';
      return;
    }

    // Remove existing static placeholder items
    grid.querySelectorAll('.gallery-item[data-static]').forEach(el => el.remove());

    images.forEach(img => {
      const item = document.createElement('div');
      item.className = 'gallery-item scroll-reveal';
      // data-cat can be set by filename prefix: e.g. "training_photo1.jpg" → cat=training
      const catMatch = img.name.match(/^([a-z]+)_/i);
      const cat = catMatch ? catMatch[1].toLowerCase() : 'general';
      item.dataset.cat = cat;
      item.innerHTML = `
        <img src="${img.download_url}" alt="${img.name}" loading="lazy"
             onerror="this.parentElement.style.display='none'"/>
        <div class="gallery-item-overlay"><span class="view-btn">🔍 View</span></div>`;
      item.querySelector('.view-btn').addEventListener('click', e => {
        e.stopPropagation();
        openLightbox(img.download_url);
      });
      item.querySelector('img').addEventListener('click', () => openLightbox(img.download_url));
      grid.appendChild(item);

      // trigger scroll-reveal
      setTimeout(() => item.classList.add('visible'), 30);
    });

    // Re-run filter if one is already active
    const activeFilter = document.querySelector('.filter-btn.active');
    if (activeFilter && activeFilter.dataset.filter !== 'all') {
      activeFilter.click();
    }

  } catch (err) {
    if (loader) loader.style.display = 'none';
    console.warn('Gallery load failed:', err);
    if (emptyMsg) {
      emptyMsg.textContent = 'Could not load gallery. Please try again later.';
      emptyMsg.style.display = 'block';
    }
  }
}
